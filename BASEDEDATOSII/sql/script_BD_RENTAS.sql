ALTER TABLE AEROLINEA ADD CONSTRAINT PK_AEROLINEA PRIMARY KEY (idaerolinea);
ALTER TABLE AVION ADD CONSTRAINT PK_AVION PRIMARY KEY (idavion);
ALTER TABLE AEROPUERTO ADD CONSTRAINT PK_AEROPUERTO PRIMARY KEY (idaeropuerto);
ALTER TABLE ASIENTO ADD CONSTRAINT PK_ASIENTO PRIMARY KEY (idasiento);
ALTER TABLE TARIFA ADD CONSTRAINT PK_TARIFA PRIMARY KEY (idtarifa);
ALTER TABLE PASAJERO ADD CONSTRAINT PK_PASAJERO PRIMARY KEY (idpasajero);
ALTER TABLE VUELO ADD CONSTRAINT PK_VUELO PRIMARY KEY (idreserva); -- O llave compuesta según diagrama si aplica
