ALTER TABLE AVION ADD CONSTRAINT FK_AVION_AEROLINEA FOREIGN KEY (idaerolinea) REFERENCES AEROLINEA(idaerolinea);
ALTER TABLE AEROPUERTO ADD CONSTRAINT FK_AEROPUERTO_PAIS FOREIGN KEY (idpais) REFERENCES PAIS(idpais);
ALTER TABLE PASAJERO ADD CONSTRAINT FK_PASAJERO_PAIS FOREIGN KEY (idpais) REFERENCES PAIS(idpais);
ALTER TABLE VUELO ADD CONSTRAINT FK_VUELO_ASIENTO FOREIGN KEY (idasiento) REFERENCES ASIENTO(idasiento);
ALTER TABLE VUELO ADD CONSTRAINT FK_VUELO_AEROPUERTO FOREIGN KEY (idaeropuerto) REFERENCES AEROPUERTO(idaeropuerto);
ALTER TABLE VUELO ADD CONSTRAINT FK_VUELO_AVION FOREIGN KEY (idavion) REFERENCES AVION(idavion);
ALTER TABLE VUELO ADD CONSTRAINT FK_VUELO_TARIFA FOREIGN KEY (idtarifa) REFERENCES TARIFA(idtarifa);
