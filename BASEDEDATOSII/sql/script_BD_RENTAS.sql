--### CASO PROPUESTO 02: COLEGIO (`BD_COLEGIO`)
--*Nota: Las claves primarias y foráneas se asignan posterior a la creación de las tablas utilizando instrucciones `ALTER TABLE`.*

--```sql
-- =========================================================================
-- CASO 02: BASE DE DATOS BD_COLEGIO
-- =========================================================================

-- 1. Cree la base de datos BD_COLEGIO y 3. Valide su existencia
IF NOT EXISTS (SELECT * FROM sys.databases WHERE name = 'BD_COLEGIO')
BEGIN
    CREATE DATABASE BD_COLEGIO;
END
GO

-- 2. Active la base de datos BD_COLEGIO
USE BD_COLEGIO;
GO

-- Limpieza si ya existen
IF OBJECT_ID('NOTAS', 'U') IS NOT NULL DROP TABLE NOTAS;
IF OBJECT_ID('ALUMNO', 'U') IS NOT NULL DROP TABLE ALUMNO;
IF OBJECT_ID('CURSO', 'U') IS NOT NULL DROP TABLE CURSO;
IF OBJECT_ID('COLEGIO', 'U') IS NOT NULL DROP TABLE COLEGIO;
IF OBJECT_ID('UBIGEO', 'U') IS NOT NULL DROP TABLE UBIGEO;
GO

-- 4, 11, 12. Creación de tablas base (sin restricciones)
CREATE TABLE UBIGEO (
    IDUBIGEO CHAR(6) NOT NULL,
    DISTRITO VARCHAR(50) NOT NULL,
    PROVINCIA VARCHAR(50) NOT NULL,
    DEPARTAMENTO VARCHAR(50) NOT NULL
);
GO

CREATE TABLE COLEGIO (
    IDCOLEGIO CHAR(5) NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    DIRECCION VARCHAR(100) NOT NULL,
    TIPO VARCHAR(30) NOT NULL,
    IDUBIGEO CHAR(6) NOT NULL
);
GO

CREATE TABLE CURSO (
    IDCURSO CHAR(5) NOT NULL,
    NOMBRECURSO VARCHAR(60) NOT NULL,
    HORASTEORICAS INT NOT NULL,
    HORASPRACTICAS INT NOT NULL,
    NIVEL VARCHAR(30) NOT NULL,
    GRADO VARCHAR(20) NOT NULL
);
GO

CREATE TABLE ALUMNO (
    IDALUMNO CHAR(8) NOT NULL,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDOS VARCHAR(80) NOT NULL,
    FECHANAC DATE NOT NULL,
    TELEFONO VARCHAR(15) NULL,
    SEXO CHAR(1) NOT NULL,
    E_MAIL VARCHAR(50) NULL,
    IDUBIGEO CHAR(6) NOT NULL
);
GO

CREATE TABLE NOTAS (
    IDCURSO CHAR(5) NOT NULL,
    IDALUMNO CHAR(8) NOT NULL,
    B1 DECIMAL(4,2) NULL,
    B2 DECIMAL(4,2) NULL,
    B3 DECIMAL(4,2) NULL,
    B4 DECIMAL(4,2) NULL,
    PROMEDIO DECIMAL(4,2) NULL
);
GO

-- 6. Agregue las llaves Primarias usando ALTER TABLE
ALTER TABLE UBIGEO ADD CONSTRAINT PK_UBIGEO PRIMARY KEY (IDUBIGEO);
ALTER TABLE COLEGIO ADD CONSTRAINT PK_COLEGIO PRIMARY KEY (IDCOLEGIO);
ALTER TABLE CURSO ADD CONSTRAINT PK_CURSO PRIMARY KEY (IDCURSO);
ALTER TABLE ALUMNO ADD CONSTRAINT PK_ALUMNO PRIMARY KEY (IDALUMNO);
ALTER TABLE NOTAS ADD CONSTRAINT PK_NOTAS PRIMARY KEY (IDCURSO, IDALUMNO);
GO

-- 7. Agregue las llaves Foráneas (Relaciones) usando ALTER TABLE
ALTER TABLE COLEGIO ADD CONSTRAINT FK_COLEGIO_UBIGEO FOREIGN KEY (IDUBIGEO) REFERENCES UBIGEO(IDUBIGEO);
ALTER TABLE ALUMNO ADD CONSTRAINT FK_ALUMNO_UBIGEO FOREIGN KEY (IDUBIGEO) REFERENCES UBIGEO(IDUBIGEO);
ALTER TABLE NOTAS ADD CONSTRAINT FK_NOTAS_CURSO FOREIGN KEY (IDCURSO) REFERENCES CURSO(IDCURSO);
ALTER TABLE NOTAS ADD CONSTRAINT FK_NOTAS_ALUMNO FOREIGN KEY (IDALUMNO) REFERENCES ALUMNO(IDALUMNO);
GO

-- 8 y 9. Agregue campo direccion (varchar 80) y telef_movil (char 9) a alumno
ALTER TABLE ALUMNO ADD direccion VARCHAR(80) NULL;
ALTER TABLE ALUMNO ADD telef_movil CHAR(9) NULL;
GO

-- 10. Elimine el campo teléfono de la tabla alumno
ALTER TABLE ALUMNO DROP COLUMN TELEFONO;
GO

-- 5 y 13. Validar existencia de tablas
SELECT name AS Tabla_Creada FROM sys.tables WHERE type = 'U';
GO
