--```sql
-- =========================================================================
-- CASO DE REFORZAMIENTO: BASE DE DATOS BD_RESERVAVUELOS
-- =========================================================================

-- 1. Cree la base de datos BD_RESERVAVUELOS de manera estándar y 3. Valide existencia
IF NOT EXISTS (SELECT * FROM sys.databases WHERE name = 'BD_RESERVAVUELOS')
