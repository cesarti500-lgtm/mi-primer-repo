GO

CREATE TABLE VUELO (
    idasiento CHAR(4) NOT NULL,
    idaeropuerto CHAR(4) NOT NULL,
    idreserva CHAR(8) NOT NULL,
    idavion CHAR(5) NOT NULL,
    idtarifa CHAR(4) NOT NULL
);
GO

-- 6. Agregue las llaves Primarias (ADD PRIMARY KEY) mediante ALTER TABLE
