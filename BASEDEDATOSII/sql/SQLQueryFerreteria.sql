USE master;
GO

-- 1. Validar y eliminar existencia previa
IF DB_ID('BD_FERRETERIA') IS NOT NULL
BEGIN
    ALTER DATABASE BD_FERRETERIA SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE BD_FERRETERIA;
END;
GO

-- 2. Creación con archivos físicos
CREATE DATABASE BD_FERRETERIA
ON PRIMARY
(
    NAME       = BD_FERRETERIA_PRI,
    FILENAME   = 'D:\FERRETERIA\DATOS\BD_FERRETERIA_PRI.mdf',
    SIZE       = 10MB,
    MAXSIZE    = 200MB,
    FILEGROWTH = 15%
)
LOG ON
(
    NAME       = BD_FERRETERIA_TRA,
    FILENAME   = 'D:\FERRETERIA\TRANS\BD_FERRETERIA_TRA.ldf',
    SIZE       = 8MB,
    MAXSIZE    = 80MB,
    FILEGROWTH = 8%
);
GO

-- 3. Modificaciones al archivo de transacciones
ALTER DATABASE BD_FERRETERIA
MODIFY FILE
(
    NAME       = BD_FERRETERIA_TRA,
    SIZE       = 25MB,
    FILEGROWTH = 17%
);
GO

-- 4. Agregar cuatro archivos secundarios
ALTER DATABASE BD_FERRETERIA
ADD FILE
(
    NAME       = BD_FERRETERIA_SEC1,
    FILENAME   = 'D:\FERRETERIA\SECUNDARIOS\BD_FERRETERIA_SEC1.ndf',
    SIZE       = 10MB,
    MAXSIZE    = 100MB,
    FILEGROWTH = 10%
),
(
    NAME       = BD_FERRETERIA_SEC2,
    FILENAME   = 'D:\FERRETERIA\SECUNDARIOS\BD_FERRETERIA_SEC2.ndf',
    SIZE       = 10MB,
    MAXSIZE    = 100MB,
    FILEGROWTH = 10%
),
(
    NAME       = BD_FERRETERIA_SEC3,
    FILENAME   = 'D:\FERRETERIA\SECUNDARIOS\BD_FERRETERIA_SEC3.ndf',
    SIZE       = 10MB,
    MAXSIZE    = 100MB,
    FILEGROWTH = 10%
),
(
    NAME       = BD_FERRETERIA_SEC4,
    FILENAME   = 'D:\FERRETERIA\SECUNDARIOS\BD_FERRETERIA_SEC4.ndf',
    SIZE       = 10MB,
    MAXSIZE    = 100MB,
    FILEGROWTH = 10%
);
GO

-- 5. Eliminar archivos secundarios SEC3 y SEC4
ALTER DATABASE BD_FERRETERIA
REMOVE FILE BD_FERRETERIA_SEC3;
GO

ALTER DATABASE BD_FERRETERIA
REMOVE FILE BD_FERRETERIA_SEC4;
GO

-- 6. Verificación de archivos
EXEC sp_helpdb 'BD_FERRETERIA';
GO
