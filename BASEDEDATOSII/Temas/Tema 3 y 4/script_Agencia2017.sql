USE master;
GO

IF DB_ID('AGENCIA2017') IS NOT NULL
BEGIN
    ALTER DATABASE AGENCIA2017 SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE AGENCIA2017;
END;
GO

CREATE DATABASE AGENCIA2017;
GO

USE AGENCIA2017;
GO

CREATE TABLE PAIS (
    IDPAIS CHAR(3)     NOT NULL,
    PAIS   VARCHAR(40) NOT NULL UNIQUE,
    CONSTRAINT PK_PAIS PRIMARY KEY (IDPAIS)
);
GO

CREATE TABLE PASAJERO (
    IDPASAJERO CHAR(6)     NOT NULL,
    NOMBRES    VARCHAR(50) NOT NULL,
    IDPAIS     CHAR(3)     NOT NULL,
    TELEFONO   VARCHAR(15) NOT NULL DEFAULT '000-0000',
    EMAIL      VARCHAR(50) NOT NULL UNIQUE,
    CONSTRAINT PK_PASAJERO PRIMARY KEY (IDPASAJERO),
    CONSTRAINT FK_PASAJERO_PAIS FOREIGN KEY (IDPAIS) REFERENCES PAIS(IDPAIS)
);
GO

CREATE TABLE RESERVA (
    IDRESERVA CHAR(8)     NOT NULL,
    COSTO     DECIMAL(10,2) NOT NULL CHECK (COSTO > 0),
    FECHA     DATE        NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_RESERVA PRIMARY KEY (IDRESERVA)
);
GO

CREATE TABLE PAGO (
    NUMPAGO    INT IDENTITY(1,1) NOT NULL,
    IDRESERVA  CHAR(8)           NOT NULL,
    IDPASAJERO CHAR(6)           NOT NULL,
    FECHA      DATE              NOT NULL CHECK (FECHA >= CAST(GETDATE() AS DATE)),
    MONTO      DECIMAL(10,2)     NOT NULL CHECK (MONTO > 0),
    CONSTRAINT PK_PAGO PRIMARY KEY (NUMPAGO),
    CONSTRAINT FK_PAGO_RESERVA FOREIGN KEY (IDRESERVA) REFERENCES RESERVA(IDRESERVA),
    CONSTRAINT FK_PAGO_PASAJERO FOREIGN KEY (IDPASAJERO) REFERENCES PASAJERO(IDPASAJERO)
);
GO
