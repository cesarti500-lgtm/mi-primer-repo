USE master;
GO

IF DB_ID('BD_COMERCIALANGULO') IS NOT NULL
BEGIN
    ALTER DATABASE BD_COMERCIALANGULO SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE BD_COMERCIALANGULO;
END;
GO

CREATE DATABASE BD_COMERCIALANGULO;
GO

USE BD_COMERCIALANGULO;
GO

-- 1. DISTRITO
CREATE TABLE DISTRITO (
    COD_DIST     CHAR(3)     NOT NULL,
    DESCRIP_DIST VARCHAR(40) NOT NULL UNIQUE,
    CONSTRAINT PK_DISTRITO PRIMARY KEY (COD_DIST)
);
GO

-- 2. EMPLEADO (con recursividad y restricciones)
CREATE TABLE EMPLEADO (
    COD_EMP          CHAR(5)     NOT NULL,
    NOMBRES_EMP      VARCHAR(30) NOT NULL,
    APE_PATER_EMP    VARCHAR(30) NOT NULL,
    APE_MATER_EMP    VARCHAR(30) NOT NULL,
    FECHA_NAC_EMP    DATE        NOT NULL,
    DIRECCION_EMP    VARCHAR(80) NOT NULL,
    TELEFONO_EMP     VARCHAR(15) NOT NULL DEFAULT '000-0000',
    COD_DIST_EMP     CHAR(3)     NOT NULL,
    CORRBO_E_EMP     VARCHAR(50) NOT NULL UNIQUE,
    FECHA_INGRESO_EMP DATE       NOT NULL DEFAULT GETDATE(),
    COD_SUPERVISOR   CHAR(5)     NULL,
    CONSTRAINT PK_EMPLOYEE PRIMARY KEY (COD_EMP),
    CONSTRAINT FK_EMP_DISTRITO FOREIGN KEY (COD_DIST_EMP) REFERENCES DISTRITO(COD_DIST),
    CONSTRAINT FK_EMP_SUPERVISOR FOREIGN KEY (COD_SUPERVISOR) REFERENCES EMPLEADO(COD_EMP)
);
GO

-- 3. CLIENTE y Subtipos
CREATE TABLE CLIENTE (
    COD_CLI      CHAR(5)     NOT NULL,
    DIRECCION_CLI VARCHAR(80) NOT NULL,
    TELEFONO_CLI VARCHAR(15) NOT NULL DEFAULT '000-0000',
    COD_DIST_CLI CHAR(3)     NOT NULL,
    CORREO_E     VARCHAR(50) NOT NULL UNIQUE,
    WEB          VARCHAR(50) NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (COD_CLI),
    CONSTRAINT FK_CLI_DISTRITO FOREIGN KEY (COD_DIST_CLI) REFERENCES DISTRITO(COD_DIST)
);
GO

CREATE TABLE CLIENTE_PER_JURIDICA (
    COD_CLI         CHAR(5)     NOT NULL,
    RAZON_SOCIAL_CLI VARCHAR(60) NOT NULL UNIQUE,
    RUC_CLI         CHAR(11)    NOT NULL UNIQUE,
    CONTACTO_CLI    VARCHAR(50) NOT NULL,
    COD_CARGO_CLI   VARCHAR(30) NOT NULL,
    CONSTRAINT PK_CLI_JURIDICA PRIMARY KEY (COD_CLI),
    CONSTRAINT FK_JURIDICA_CLIENTE FOREIGN KEY (COD_CLI) REFERENCES CLIENTE(COD_CLI)
);
GO

CREATE TABLE CLIENTE_PER_NATURAL (
    COD_CLI       CHAR(5)     NOT NULL,
    NOMBRES_CLI   VARCHAR(30) NOT NULL,
    APE_PATER_CLI VARCHAR(30) NOT NULL,
    APE_MATER_CLI VARCHAR(30) NOT NULL,
    CONSTRAINT PK_CLI_NATURAL PRIMARY KEY (COD_CLI),
    CONSTRAINT FK_NATURAL_CLIENTE FOREIGN KEY (COD_CLI) REFERENCES CLIENTE(COD_CLI)
);
GO

-- 4. TIPO_PRODUCTO y PRODUCTO
CREATE TABLE TIPO_PRODUCTO (
    COD_TIPO_PRO     CHAR(3)     NOT NULL,
    DESCRIP_TIPO_PRO VARCHAR(40) NOT NULL UNIQUE,
    CONSTRAINT PK_TIPO_PRODUCTO PRIMARY KEY (COD_TIPO_PRO)
);
GO

CREATE TABLE PRODUCTO (
    COD_PRO        CHAR(6)       NOT NULL,
    DESCRIP_PRO    VARCHAR(50)   NOT NULL UNIQUE,
    PRECIO_PRO     DECIMAL(10,2) NOT NULL CHECK (PRECIO_PRO > 0),
    STOCK_ACT_PRO  INT           NOT NULL DEFAULT 0 CHECK (STOCK_ACT_PRO >= 0),
    STOCK_MIN_PRO  INT           NOT NULL DEFAULT 5 CHECK (STOCK_MIN_PRO >= 0),
    COD_TIPO_PRO   CHAR(3)       NOT NULL,
    CONSTRAINT PK_PRODUCTO PRIMARY KEY (COD_PRO),
    CONSTRAINT FK_PRODUCTO_TIPO FOREIGN KEY (COD_TIPO_PRO) REFERENCES TIPO_PRODUCTO(COD_TIPO_PRO)
);
GO

-- 5. BOLETA y DETALLEBOLETA (con IDENTITY)
CREATE TABLE BOLETA (
    COD_BOL    INT IDENTITY(1000,1) NOT NULL,
    COD_EMP    CHAR(5)              NOT NULL,
    FECHA_BOL  DATE                 NOT NULL DEFAULT GETDATE(),
    COD_CLI    CHAR(5)              NOT NULL,
    ESTADO_BOL CHAR(2)              NOT NULL DEFAULT '01' CHECK (ESTADO_BOL IN ('01', '02', '03')),
    CONSTRAINT PK_BOLETA PRIMARY KEY (COD_BOL),
    CONSTRAINT FK_BOLETA_EMPLEADO FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP),
    CONSTRAINT FK_BOLETA_CLIENTE FOREIGN KEY (COD_CLI) REFERENCES CLIENTE(COD_CLI)
);
GO

CREATE TABLE DETALLEBOLETA (
    COD_BOL     INT           NOT NULL,
    COD_PRO     CHAR(6)       NOT NULL,
    CANTIDAD    INT           NOT NULL CHECK (CANTIDAD > 0),
    PRECIOVENTA DECIMAL(10,2) NOT NULL CHECK (PRECIOVENTA > 0),
    CONSTRAINT PK_DETALLEBOLETA PRIMARY KEY (COD_BOL, COD_PRO),
    CONSTRAINT FK_DETALLE_BOLETA FOREIGN KEY (COD_BOL) REFERENCES BOLETA(COD_BOL),
    CONSTRAINT FK_DETALLE_PRODUCTO FOREIGN KEY (COD_PRO) REFERENCES PRODUCTO(COD_PRO)
);
GO
