-- 1. Al crear la tabla
CREATE TABLE EMPLEADO_DEF (
    IDEMPLEADO    INT          NOT NULL PRIMARY KEY,
    NOMBRE_EMP    VARCHAR(30)  NOT NULL,
    TELEFONO_EMP  CHAR(15)     DEFAULT '000-000000',
    EST_CIVIL_EMP CHAR(1)      DEFAULT 'S',
    SUELDO_EMP    MONEY        DEFAULT 0,
    NUM_HIJOS_EMP INT          DEFAULT 0
);
GO

-- 2. A una tabla ya existente
ALTER TABLE EMPLEADO_DEF ADD DEFAULT '000-000000' FOR TELEFONO_EMP;
ALTER TABLE EMPLEADO_DEF ADD DEFAULT 'S' FOR EST_CIVIL_EMP;
GO

-- 3. Con funciones del sistema (GETDATE)
ALTER TABLE EMPLEADO_DEF ADD FECHA_INGRESO DATE DEFAULT GETDATE();
GO


-- 1. Al crear la tabla con validación de rangos y listas
CREATE TABLE EMPLEADO_CHK (
    IDEMPLEADO    INT          NOT NULL PRIMARY KEY,
    EST_CIVIL_EMP CHAR(1)      NOT NULL CHECK (EST_CIVIL_EMP IN ('S', 'C', 'V', 'D')),
    SUELDO_EMP    MONEY        NOT NULL CHECK (SUELDO_EMP >= 1000 AND SUELDO_EMP <= 2500),
    NUM_HIJOS_EMP INT          NOT NULL CHECK (NUM_HIJOS_EMP >= 0)
);
GO

-- 2. Añadir CHECK mediante ALTER TABLE
ALTER TABLE EMPLEADO_CHK
ADD CONSTRAINT CHK_SUELDO_RANGO CHECK (SUELDO_EMP BETWEEN 850 AND 6000);
GO

-- 1. Al crear la tabla
CREATE TABLE EMPLEADO_UNI (
    IDEMPLEADO   INT          NOT NULL PRIMARY KEY,
    TELEFONO_EMP CHAR(15)     NULL UNIQUE,
    CORREO_EMP   VARCHAR(40)  NOT NULL UNIQUE
);
GO

-- 2. Añadir UNIQUE mediante ALTER TABLE
ALTER TABLE EMPLEADO_UNI
ADD CONSTRAINT UQ_CORREO_EMP UNIQUE (CORREO_EMP);
GO


-- Autoincremental de 100 en 100 con incremento de 1
CREATE TABLE DETALLE_BOLETA_ID (
    nro_item     INT IDENTITY (100, 1),
    nro_boleta   CHAR(8)      NOT NULL,
    cod_prod     CHAR(6)      NOT NULL,
    cantidad     INT          NOT NULL,
    precio_venta NUMERIC(8,2) NOT NULL,
    CONSTRAINT PK_DETALLE_ID PRIMARY KEY (nro_item)
);
GO

