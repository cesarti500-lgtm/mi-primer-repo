USE master;
GO

-- 1. Validar y crear la base de datos
IF DB_ID('BD_COLEGIO') IS NOT NULL
BEGIN
    ALTER DATABASE BD_COLEGIO SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE BD_COLEGIO;
END;
GO

CREATE DATABASE BD_COLEGIO;
GO

USE BD_COLEGIO;
GO

-- 2. Creación de tablas sin restricciones
CREATE TABLE UBIGEO
(
    IDUBIGEO     CHAR(6)     NOT NULL,
    DISTRITO     VARCHAR(40) NOT NULL,
    PROVINCIA    VARCHAR(40) NOT NULL,
    DEPARTAMENTO VARCHAR(40) NOT NULL
);
GO

CREATE TABLE CURSO
(
    IDCURSO        CHAR(5)     NOT NULL,
    NOMBRECURSO    VARCHAR(50) NOT NULL,
    HORASTEORICAS  INT         NOT NULL,
    HORASPRACTICAS INT         NOT NULL,
    NIVEL          VARCHAR(20) NOT NULL,
    GRADO          VARCHAR(20) NOT NULL
);
GO

CREATE TABLE COLEGIO
(
    IDCOLEGIO CHAR(5)      NOT NULL,
    NOMBRE    VARCHAR(60)  NOT NULL,
    DIRECCION VARCHAR(100) NOT NULL,
    TIPO      VARCHAR(20)  NOT NULL,
    IDUBIGEO  CHAR(6)      NOT NULL
);
GO

CREATE TABLE ALUMNO
(
    IDALUMNO  CHAR(6)     NOT NULL,
    NOMBRE    VARCHAR(30) NOT NULL,
    APELLIDOS VARCHAR(50) NOT NULL,
    FECHANAC  DATE        NOT NULL,
    TELEFONO  VARCHAR(15) NULL,
    SEXO      CHAR(1)     NOT NULL,
    E_MAIL    VARCHAR(50) NULL,
    IDUBIGEO  CHAR(6)     NOT NULL
);
GO

CREATE TABLE NOTAS
(
    IDCURSO  CHAR(5)       NOT NULL,
    IDALUMNO CHAR(6)       NOT NULL,
    B1       DECIMAL(4,2)  NULL,
    B2       DECIMAL(4,2)  NULL,
    B3       DECIMAL(4,2)  NULL,
    B4       DECIMAL(4,2)  NULL,
    PROMEDIO DECIMAL(4,2)  NULL
);
GO

-- 3. Agregar Llaves Primarias (ADD PRIMARY KEY)
ALTER TABLE UBIGEO
ADD CONSTRAINT PK_UBIGEO PRIMARY KEY (IDUBIGEO);
GO

ALTER TABLE CURSO
ADD CONSTRAINT PK_CURSO PRIMARY KEY (IDCURSO);
GO

ALTER TABLE COLEGIO
ADD CONSTRAINT PK_COLEGIO PRIMARY KEY (IDCOLEGIO);
GO

ALTER TABLE ALUMNO
ADD CONSTRAINT PK_ALUMNO PRIMARY KEY (IDALUMNO);
GO

ALTER TABLE NOTAS
ADD CONSTRAINT PK_NOTAS PRIMARY KEY (IDCURSO, IDALUMNO);
GO

-- 4. Agregar Llaves Foráneas (ADD FOREIGN KEY REFERENCES)
ALTER TABLE COLEGIO
ADD CONSTRAINT FK_COLEGIO_UBIGEO 
FOREIGN KEY (IDUBIGEO) REFERENCES UBIGEO(IDUBIGEO);
GO

ALTER TABLE ALUMNO
ADD CONSTRAINT FK_ALUMNO_UBIGEO 
FOREIGN KEY (IDUBIGEO) REFERENCES UBIGEO(IDUBIGEO);
GO

ALTER TABLE NOTAS
ADD CONSTRAINT FK_NOTAS_CURSO 
FOREIGN KEY (IDCURSO) REFERENCES CURSO(IDCURSO);
GO

ALTER TABLE NOTAS
ADD CONSTRAINT FK_NOTAS_ALUMNO 
FOREIGN KEY (IDALUMNO) REFERENCES ALUMNO(IDALUMNO);
GO

-- 5. Modificaciones con ALTER TABLE
-- Agregar dirección (varchar 80)
ALTER TABLE ALUMNO
ADD DIRECCION VARCHAR(80) NULL;
GO

-- Agregar telef_movil (char 9)
ALTER TABLE ALUMNO
ADD TELEF_MOVIL CHAR(9) NULL;
GO

-- Eliminar campo teléfono
ALTER TABLE ALUMNO
DROP COLUMN TELEFONO;
GO
