USE master;
GO

-- 1. Validar y crear la base de datos
IF DB_ID('BD_RENTA') IS NOT NULL
BEGIN
    ALTER DATABASE BD_RENTA SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE BD_RENTA;
END;
GO

CREATE DATABASE BD_RENTA;
GO

USE BD_RENTA;
GO

-- 2. Crear tablas maestras
CREATE TABLE TB_MARCA
(
    COD_MARCA CHAR(4)       NOT NULL,
    NOM_MARCA VARCHAR(30)   NOT NULL,
    FEC_ING   DATE          NOT NULL,
    PAIS_PROC VARCHAR(30)   NOT NULL,
    CONSTRAINT PK_TB_MARCA PRIMARY KEY (COD_MARCA)
);
GO

CREATE TABLE TB_CLIENTE
(
    COD_CLI     CHAR(5)     NOT NULL,
    NOM_CLI     VARCHAR(30) NOT NULL,
    APE_PAT_CLI VARCHAR(30) NOT NULL,
    APE_MAT_CLI VARCHAR(30) NOT NULL,
    FEC_NAC_CLI DATE        NULL,
    TIPO_CLI    VARCHAR(20) NOT NULL,
    CONSTRAINT PK_TB_CLIENTE PRIMARY KEY (COD_CLI)
);
GO

CREATE TABLE TB_AUTOMOVIL
(
    COD_AUTO    CHAR(6)       NOT NULL,
    MODELO_AUTO VARCHAR(30)   NOT NULL,
    FEC_AUTO    DATE          NOT NULL,
    COLOR_AUTO  VARCHAR(20)   NOT NULL,
    PRECIO_AUTO DECIMAL(10,2) NOT NULL,
    COD_MARCA   CHAR(4)       NOT NULL,
    CONSTRAINT PK_TB_AUTOMOVIL PRIMARY KEY (COD_AUTO),
    CONSTRAINT FK_TB_AUTOMOVIL_TB_MARCA FOREIGN KEY (COD_MARCA) 
        REFERENCES TB_MARCA(COD_MARCA)
);
GO

-- 3. Crear tabla transaccional (Alquiler) con PK compuesta y FKs
CREATE TABLE TB_ALQUILER
(
    COD_AUTO     CHAR(6) NOT NULL,
    COD_CLI      CHAR(5) NOT NULL,
    FEC_INI_ASIG DATE    NOT NULL,
    FEC_FIN_ASIG DATE    NULL,
    CONSTRAINT PK_TB_ALQUILER PRIMARY KEY (COD_AUTO, COD_CLI),
    CONSTRAINT FK_TB_ALQUILER_TB_AUTOMOVIL FOREIGN KEY (COD_AUTO) 
        REFERENCES TB_AUTOMOVIL(COD_AUTO),
    CONSTRAINT FK_TB_ALQUILER_TB_CLIENTE FOREIGN KEY (COD_CLI) 
        REFERENCES TB_CLIENTE(COD_CLI)
);
GO

-- 4. Modificaciones con ALTER TABLE
-- Agregar dirección (varchar 80)
ALTER TABLE TB_CLIENTE
ADD DIRECCION VARCHAR(80) NULL;
GO

-- Agregar email (varchar 35)
ALTER TABLE TB_CLIENTE
ADD EMAIL VARCHAR(35) NULL;
GO

-- Eliminar fecha de nacimiento (FEC_NAC_CLI)
ALTER TABLE TB_CLIENTE
DROP COLUMN FEC_NAC_CLI;
GO
