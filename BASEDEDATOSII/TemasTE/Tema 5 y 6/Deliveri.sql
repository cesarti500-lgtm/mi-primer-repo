-- ==================== CREACIÓN DE TABLAS ====================
CREATE TABLE BREVETE (
    COD_BREV CHAR(5) NOT NULL,
    DES_BREV VARCHAR(30) NOT NULL,
    CONSTRAINT PK_BREVETE PRIMARY KEY (COD_BREV)
);

CREATE TABLE REPARTIDOR (
    COD_REP CHAR(5) NOT NULL,
    COD_BREV CHAR(5) NOT NULL,
    NOM_REP VARCHAR(30) NOT NULL,
    APE_PAT_REP VARCHAR(30) NOT NULL,
    APE_MAT_REP VARCHAR(30) NOT NULL,
    FEC_ING DATETIME NOT NULL,
    DNI_REP CHAR(8) NOT NULL,
    CONSTRAINT PK_REPARTIDOR PRIMARY KEY (COD_REP),
    CONSTRAINT FK_REPARTIDOR_BREVETE FOREIGN KEY (COD_BREV) REFERENCES BREVETE(COD_BREV)
);

CREATE TABLE DESAYUNO (
    COD_DES CHAR(5) NOT NULL,
    DESC_DES VARCHAR(30) NOT NULL,
    PRECIO_DES DECIMAL(10,2) NULL,
    FEC_ING DATETIME NOT NULL,
    CONSTRAINT PK_DESAYUNO PRIMARY KEY (COD_DES)
);

CREATE TABLE PEDIDO (
    COD_PED CHAR(5) NOT NULL,
    COD_REP CHAR(5) NOT NULL,
    FEC_PED DATETIME NOT NULL,
    EST_PED INT NOT NULL,
    CONSTRAINT PK_PEDIDO PRIMARY KEY (COD_PED),
    CONSTRAINT FK_PEDIDO_REPARTIDOR FOREIGN KEY (COD_REP) REFERENCES REPARTIDOR(COD_REP)
);

CREATE TABLE DETALLE_PEDIDO (
    COD_PED CHAR(5) NOT NULL,
    COD_DES CHAR(5) NOT NULL,
    CANTIDAD INT NOT NULL,
    PRECIO_DES DECIMAL(10,2) NULL,
    CONSTRAINT PK_DETALLE_PEDIDO PRIMARY KEY (COD_PED, COD_DES),
    CONSTRAINT FK_DETALLE_PEDIDO FOREIGN KEY (COD_PED) REFERENCES PEDIDO(COD_PED),
    CONSTRAINT FK_DETALLE_DESAYUNO FOREIGN KEY (COD_DES) REFERENCES DESAYUNO(COD_DES)
);
GO

