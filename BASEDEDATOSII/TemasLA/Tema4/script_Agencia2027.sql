USE master;
GO

IF DB_ID('AGENCIA2017') IS NOT NULL
    DROP DATABASE AGENCIA2017;
GO

CREATE DATABASE AGENCIA2017;
GO

USE AGENCIA2017;
GO

-- Tabla: PAIS
CREATE TABLE PAIS (
    IDPAIS CHAR(4) NOT NULL,
    PAIS VARCHAR(80) NOT NULL,
    CONSTRAINT PK_PAIS PRIMARY KEY (IDPAIS),
    CONSTRAINT UQ_PAIS_NOMBRE UNIQUE (PAIS)
);
GO

-- Tabla: PASAJERO
CREATE TABLE PASAJERO (
    IDPASAJERO CHAR(6) NOT NULL,
    NOMBRES VARCHAR(120) NOT NULL,
    IDPAIS CHAR(4) NOT NULL,
    TELEFONO VARCHAR(15) NOT NULL CONSTRAINT DF_PASAJERO_TELEFONO DEFAULT '000-0000',
    EMAIL VARCHAR(100) NOT NULL,
    CONSTRAINT PK_PASAJERO PRIMARY KEY (IDPASAJERO),
    CONSTRAINT UQ_PASAJERO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_PASAJERO_PAIS FOREIGN KEY (IDPAIS) REFERENCES PAIS(IDPAIS)
);
GO

-- Tabla: RESERVA
CREATE TABLE RESERVA (
    IDRESERVA CHAR(6) NOT NULL,
    COSTO DECIMAL(10,2) NOT NULL,
    FECHA DATE NOT NULL CONSTRAINT DF_RESERVA_FECHA DEFAULT CAST(GETDATE() AS DATE),
    CONSTRAINT PK_RESERVA PRIMARY KEY (IDRESERVA),
    CONSTRAINT CK_RESERVA_COSTO CHECK (COSTO > 0)
);
GO

-- Tabla: PAGO
CREATE TABLE PAGO (
    NUMPAGO INT IDENTITY(1,1) NOT NULL,
    IDRESERVA CHAR(6) NOT NULL,
    IDPASAJERO CHAR(6) NOT NULL,
    FECHA DATE NOT NULL,
    MONTO DECIMAL(10,2) NOT NULL,
    CONSTRAINT PK_PAGO PRIMARY KEY (NUMPAGO),
    CONSTRAINT CK_PAGO_FECHA CHECK (FECHA > CAST(GETDATE() AS DATE)),
    CONSTRAINT CK_PAGO_MONTO CHECK (MONTO > 0),
    CONSTRAINT FK_PAGO_RESERVA FOREIGN KEY (IDRESERVA) REFERENCES RESERVA(IDRESERVA),
    CONSTRAINT FK_PAGO_PASAJERO FOREIGN KEY (IDPASAJERO) REFERENCES PASAJERO(IDPASAJERO)
);
GO