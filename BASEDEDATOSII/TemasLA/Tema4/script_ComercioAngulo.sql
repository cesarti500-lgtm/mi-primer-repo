USE master;
GO

-- 1. Crear la base de datos BD_COMERCIALANGULO
IF DB_ID('BD_COMERCIALANGULO') IS NOT NULL
    DROP DATABASE BD_COMERCIALANGULO;
GO

CREATE DATABASE BD_COMERCIALANGULO;
GO

-- 2. Activar la base de datos BD_COMERCIALANGULO
USE BD_COMERCIALANGULO;
GO

-- 3. Crear las tablas con tipos de datos, nulidad, IDENTITY (2), DEFAULT (4), CHECK (6) y UNIQUE (4)

-- Tabla: DISTRITO (IDENTITY #1)
CREATE TABLE DISTRITO (
    COD_DIST INT IDENTITY(1,1) NOT NULL,
    DESCRIP_DIST VARCHAR(80) NOT NULL,
    CONSTRAINT UQ_DISTRITO_DESCRIP UNIQUE (DESCRIP_DIST) -- UNIQUE #1
);
GO

-- Tabla: TIPO_PRODUCTO (IDENTITY #2)
CREATE TABLE TIPO_PRODUCTO (
    COD_TIPO_PRO INT IDENTITY(1,1) NOT NULL,
    DESCRIP_TIPO_PRO VARCHAR(80) NOT NULL,
    CONSTRAINT UQ_TIPOPROD_DESCRIP UNIQUE (DESCRIP_TIPO_PRO) -- UNIQUE #2
);
GO

-- Tabla: EMPLEADO (Incluye recursividad COD_SUPERVISOR)
CREATE TABLE EMPLEADO (
    COD_EMP CHAR(5) NOT NULL,
    NOMBRES_EMP VARCHAR(60) NOT NULL,
    APE_PATER_EMP VARCHAR(50) NOT NULL,
    APE_MATER_EMP VARCHAR(50) NOT NULL,
    FECHA_NAC_EMP DATE NOT NULL,
    DIRECCION_EMP VARCHAR(150) NOT NULL,
    TELEFONO_EMP VARCHAR(15) NULL,
    CODDIST_EMP INT NOT NULL,
    CORREO_E_EMP VARCHAR(100) NOT NULL,
    FECHA_INGRESO_EMP DATE NOT NULL CONSTRAINT DF_EMPLEADO_FECING DEFAULT CAST(GETDATE() AS DATE), -- DEFAULT #1
    COD_SUPERVISOR CHAR(5) NULL,
    CONSTRAINT UQ_EMPLEADO_CORREO UNIQUE (CORREO_E_EMP), -- UNIQUE #3
    CONSTRAINT CK_EMPLEADO_EDAD CHECK (DATEDIFF(YEAR, FECHA_NAC_EMP, FECHA_INGRESO_EMP) >= 18) -- CHECK #1
);
GO

-- Tabla: CLIENTE (Superentidad)
CREATE TABLE CLIENTE (
    COD_CLI CHAR(6) NOT NULL,
    DIRECCION_CLI VARCHAR(150) NOT NULL,
    TELEFONO_CLI VARCHAR(15) NOT NULL CONSTRAINT DF_CLIENTE_TEL DEFAULT '000-0000', -- DEFAULT #2
    CODDIST_CLI INT NOT NULL,
    CORREO_E VARCHAR(100) NULL,
    WEB VARCHAR(100) NULL
);
GO

-- Tabla: CLIENTE_PER_JURIDICA (Subtipo)
CREATE TABLE CLIENTE_PER_JURIDICA (
    COD_CLI CHAR(6) NOT NULL,
    RAZONSOCIAL_CLI VARCHAR(120) NOT NULL,
    RUC_CLI CHAR(11) NOT NULL,
    CONTACTO_CLI VARCHAR(100) NOT NULL,
    COD_CARGO_CLI VARCHAR(30) NOT NULL,
    CONSTRAINT UQ_JURIDICA_RUC UNIQUE (RUC_CLI), -- UNIQUE #4
    CONSTRAINT CK_JURIDICA_RUC_LEN CHECK (LEN(RUC_CLI) = 11 AND RUC_CLI NOT LIKE '%[^0-9]%') -- CHECK #2
);
GO

-- Tabla: CLIENTE_PER_NATURAL (Subtipo)
CREATE TABLE CLIENTE_PER_NATURAL (
    COD_CLI CHAR(6) NOT NULL,
    NOMBRES_CLI VARCHAR(60) NOT NULL,
    APE_PATER_CLI VARCHAR(50) NOT NULL,
    APE_MATER_CLI VARCHAR(50) NOT NULL
);
GO

-- Tabla: PRODUCTO
CREATE TABLE PRODUCTO (
    COD_PRO CHAR(6) NOT NULL,
    DESCRIP_PRO VARCHAR(120) NOT NULL,
    PRECIO_PRO DECIMAL(10,2) NOT NULL,
    STOCK_ACT_PRO INT NOT NULL CONSTRAINT DF_PRODUCTO_STKACT DEFAULT 0, -- DEFAULT #3
    STOCK_MIN_PRO INT NOT NULL,
    COD_TIPO_PRO INT NOT NULL,
    CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO_PRO > 0), -- CHECK #3
    CONSTRAINT CK_PRODUCTO_STOCKS CHECK (STOCK_ACT_PRO >= 0 AND STOCK_MIN_PRO >= 0) -- CHECK #4
);
GO

-- Tabla: BOLETA
CREATE TABLE BOLETA (
    COD_BOL CHAR(8) NOT NULL,
    COD_EMP CHAR(5) NOT NULL,
    FECHA_BOL DATE NOT NULL,
    COD_CLI CHAR(6) NOT NULL,
    ESTADO_BOL VARCHAR(15) NOT NULL CONSTRAINT DF_BOLETA_ESTADO DEFAULT 'EMITIDA', -- DEFAULT #4
    CONSTRAINT CK_BOLETA_ESTADO CHECK (ESTADO_BOL IN ('EMITIDA', 'PAGADA', 'ANULADA')) -- CHECK #5
);
GO

-- Tabla: DETALLEBOLETA
CREATE TABLE DETALLEBOLETA (
    COD_BOL CHAR(8) NOT NULL,
    COD_PRO CHAR(6) NOT NULL,
    CANTIDAD INT NOT NULL,
    PRECIOVENTA DECIMAL(10,2) NOT NULL,
    CONSTRAINT CK_DETALLE_CANT_PREC CHECK (CANTIDAD > 0 AND PRECIOVENTA > 0) -- CHECK #6
);
GO

-- 4. Agregar Llaves Primarias (ADD PRIMARY KEY)
ALTER TABLE DISTRITO ADD CONSTRAINT PK_DISTRITO PRIMARY KEY (COD_DIST);
ALTER TABLE TIPO_PRODUCTO ADD CONSTRAINT PK_TIPO_PRODUCTO PRIMARY KEY (COD_TIPO_PRO);
ALTER TABLE EMPLEADO ADD CONSTRAINT PK_EMPLEADO PRIMARY KEY (COD_EMP);
ALTER TABLE CLIENTE ADD CONSTRAINT PK_CLIENTE PRIMARY KEY (COD_CLI);
ALTER TABLE CLIENTE_PER_JURIDICA ADD CONSTRAINT PK_CLIENTE_JURIDICA PRIMARY KEY (COD_CLI);
ALTER TABLE CLIENTE_PER_NATURAL ADD CONSTRAINT PK_CLIENTE_NATURAL PRIMARY KEY (COD_CLI);
ALTER TABLE PRODUCTO ADD CONSTRAINT PK_PRODUCTO PRIMARY KEY (COD_PRO);
ALTER TABLE BOLETA ADD CONSTRAINT PK_BOLETA PRIMARY KEY (COD_BOL);
ALTER TABLE DETALLEBOLETA ADD CONSTRAINT PK_DETALLEBOLETA PRIMARY KEY (COD_BOL, COD_PRO);
GO

-- 5. Agregar Llaves Foráneas y Relaciones (ADD FOREIGN KEY - REFERENCES)
ALTER TABLE EMPLEADO
    ADD CONSTRAINT FK_EMPLEADO_DISTRITO FOREIGN KEY (CODDIST_EMP) REFERENCES DISTRITO(COD_DIST),
        CONSTRAINT FK_EMPLEADO_SUPERVISOR FOREIGN KEY (COD_SUPERVISOR) REFERENCES EMPLEADO(COD_EMP);

ALTER TABLE CLIENTE
    ADD CONSTRAINT FK_CLIENTE_DISTRITO FOREIGN KEY (CODDIST_CLI) REFERENCES DISTRITO(COD_DIST);

ALTER TABLE CLIENTE_PER_JURIDICA
    ADD CONSTRAINT FK_JURIDICA_CLIENTE FOREIGN KEY (COD_CLI) REFERENCES CLIENTE(COD_CLI);

ALTER TABLE CLIENTE_PER_NATURAL
    ADD CONSTRAINT FK_NATURAL_CLIENTE FOREIGN KEY (COD_CLI) REFERENCES CLIENTE(COD_CLI);

ALTER TABLE PRODUCTO
    ADD CONSTRAINT FK_PRODUCTO_TIPOPROD FOREIGN KEY (COD_TIPO_PRO) REFERENCES TIPO_PRODUCTO(COD_TIPO_PRO);

ALTER TABLE BOLETA
    ADD CONSTRAINT FK_BOLETA_EMPLEADO FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP),
        CONSTRAINT FK_BOLETA_CLIENTE FOREIGN KEY (COD_CLI) REFERENCES CLIENTE(COD_CLI);

ALTER TABLE DETALLEBOLETA
    ADD CONSTRAINT FK_DETALLE_BOLETA FOREIGN KEY (COD_BOL) REFERENCES BOLETA(COD_BOL),
        CONSTRAINT FK_DETALLE_PRODUCTO FOREIGN KEY (COD_PRO) REFERENCES PRODUCTO(COD_PRO);
GO